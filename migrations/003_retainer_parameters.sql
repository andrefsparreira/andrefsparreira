CREATE TABLE IF NOT EXISTS retainer_parameters (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  kind text NOT NULL,
  sort_order integer NOT NULL,
  active integer NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS retainer_values (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parameter_id integer NOT NULL REFERENCES retainer_parameters(id) ON DELETE CASCADE,
  label text NOT NULL,
  amount double precision NOT NULL DEFAULT 0,
  range_min double precision,
  range_max double precision,
  sort_order integer NOT NULL
);

CREATE TABLE IF NOT EXISTS fee_year_choices (
  year_id integer NOT NULL REFERENCES fee_years(id) ON DELETE CASCADE,
  parameter_id integer NOT NULL REFERENCES retainer_parameters(id) ON DELETE CASCADE,
  value_id integer REFERENCES retainer_values(id) ON DELETE SET NULL,
  numeric_value double precision,
  PRIMARY KEY (year_id, parameter_id)
);

